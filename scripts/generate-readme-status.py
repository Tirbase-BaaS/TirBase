#!/usr/bin/env python3
"""Regenerate the README Status section from CLAIMS.md (CLAIM-50.2, PV-17.3).

Replaces the content between the markers:
 <!-- README-STATUS:BEGIN -->
 <!-- README-STATUS:END -->
with a summary table derived from CLAIMS.md.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

BEGIN = "<!-- README-STATUS:BEGIN -->"
END = "<!-- README-STATUS:END -->"


def parse_claims(text: str):
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|") or line.startswith("|---") or line.startswith("| Claim ID"):
            continue
        parts = [p.strip() for p in line.strip("|").split("|")]
        if len(parts) < 4:
            continue
        claim_id, claim_text, status, test_id = parts[0], parts[1], parts[2], parts[3]
        if not claim_id or claim_id == "Claim ID":
            continue
        rows.append((claim_id, claim_text, status, test_id))
    return rows


def render(rows):
    counts = Counter(status for _, _, status, _ in rows)
    proven = counts.get("Proven", 0)
    planned = counts.get("Planned", 0)
    implemented = counts.get("Implemented", 0)
    total = sum(counts.values())
    lines = [
        BEGIN,
        "## Status (generated from `CLAIMS.md`)",
        "",
        f"_Last regenerated by `scripts/generate-readme-status.py` (CLAIM-50.2). Do not edit this section manually._",
        "",
        f"- **Proven:** {proven}",
        f"- **Planned:** {planned}",
        (f"- **Implemented:** {implemented}" if implemented else None),
        f"- **Total claims:** {total}",
        "",
        "| Claim ID | Status | Test Identifier |",
        "|---|---|---|",
    ]
 # remove None
    lines = [l for l in lines if l is not None]
    for claim_id, _text, status, test_id in rows:
        tid = test_id if test_id else "—"
 # keep table cells single-line and escape pipes
        tid = tid.replace("\n", " ").replace("|", "\\|")
        claim_id = claim_id.replace("|", "\\|")
        status = status.replace("|", "\\|")
        lines.append(f"| {claim_id} | {status} | {tid} |")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    claims_path = root / "CLAIMS.md"
    readme_path = root / "README.md"
    claims_text = claims_path.read_text(encoding="utf-8")
    readme_text = readme_path.read_text(encoding="utf-8")

    rows = parse_claims(claims_text)
    if not rows:
        print("ERROR: no claim rows parsed from CLAIMS.md", file=sys.stderr)
        return 2

    block = render(rows)
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(readme_text):
 # append if markers missing
        if not readme_text.endswith("\n"):
            readme_text += "\n"
        new_text = readme_text + "\n" + block + "\n"
    else:
        new_text = pattern.sub(block, readme_text)

    if new_text != readme_text:
        readme_path.write_text(new_text, encoding="utf-8")
        print(f"updated README Status section ({len(rows)} claims)")
    else:
        print(f"README Status section already up to date ({len(rows)} claims)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
