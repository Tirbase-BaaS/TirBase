#!/usr/bin/env python3
"""Regenerate the README Status section from CLAIMS.md (CLAIM-50.2, PV-17.3).

Replaces the content between the markers:
 <!-- README-STATUS:BEGIN -->
 <!-- README-STATUS:END -->
with a summary derived from CLAIMS.md: status counts, the explicit list of claims
that are implemented but not wired (so they cannot read as done), and one row
per claim with its status, production caller, and evidence.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

BEGIN = "<!-- README-STATUS:BEGIN -->"
END = "<!-- README-STATUS:END -->"


def split_row(line: str):
    """Split a markdown row on pipes that are not inside backticks."""
    parts, current, ticks = [], [], False
    for ch in line.rstrip("\n"):
        if ch == "`":
            ticks = not ticks
            current.append(ch)
            continue
        if ch == "|" and not ticks:
            parts.append("".join(current))
            current = []
            continue
        current.append(ch)
    parts.append("".join(current))
    return [p.strip() for p in parts[1:-1]]


def parse_claims(text: str):
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("| CLAIM-"):
            continue
        parts = split_row(line)
        if len(parts) != 5:
            raise SystemExit(
                f"ERROR: claim row does not have 5 columns: {parts[0] if parts else line!r}"
            )
        claim_id, claim_text, status, caller, test_id = parts
        rows.append((claim_id, claim_text, status, caller, test_id))
    return rows


def render(rows):
    counts = Counter(status for _, _, status, _, _ in rows)
    proven = counts.get("Proven", 0)
    unproven = counts.get("Implemented and wired (unproven)", 0)
    unwired = counts.get("Implemented but not wired", 0)
    planned = counts.get("Planned", 0)
    total = sum(counts.values())

    unwired_ids = [cid for cid, _t, status, _c, _e in rows if status == "Implemented but not wired"]
    lines = [
        BEGIN,
        "## Status (generated from `CLAIMS.md`)",
        "",
        "_Last regenerated by `scripts/generate-readme-status.py` (CLAIM-50.2). Do not edit this section manually._",
        "",
        f"- **Proven:** {proven}",
        f"- **Implemented and wired (unproven):** {unproven}",
        f"- **Implemented but not wired:** {unwired}",
        f"- **Planned:** {planned}",
        f"- **Total claims:** {total}",
        "",
    ]
    if unwired_ids:
        lines.append(
            "**Not done:** the following claims are implemented but have no production caller "
            "(`CLAIMS.md` records `none — implemented but not wired`): "
            + ", ".join(unwired_ids)
            + "."
        )
        lines.append("")
    lines.append("| Claim ID | Status | Production Caller | Test or CI Gate |")
    lines.append("|---|---|---|---|")
    for claim_id, _text, status, caller, test_id in rows:
        tid = test_id if test_id else "—"
        # keep table cells single-line and escape pipes
        cells = [
            claim_id.replace("|", "\\|"),
            status.replace("|", "\\|"),
            caller.replace("\n", " ").replace("|", "\\|"),
            tid.replace("\n", " ").replace("|", "\\|"),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    claims_path = root / "CLAIMS.md"
    readme_path = root / "README.md"
    claims_text = claims_path.read_text(encoding="utf-8")
    readme_text = readme_path.read_text(encoding="utf-8")

    rows = parse_claims(claims_text)
    if not rows:
        print("ERROR: no claim rows parsed from CLAIMS.md", file=sys.stderr)
        return 2

    block = render(rows)
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(readme_text):
 # append if markers missing
        if not readme_text.endswith("\n"):
            readme_text += "\n"
        new_text = readme_text + "\n" + block + "\n"
    else:
        new_text = pattern.sub(block, readme_text)

    if new_text != readme_text:
        readme_path.write_text(new_text, encoding="utf-8")
        print(f"updated README Status section ({len(rows)} claims)")
    else:
        print(f"README Status section already up to date ({len(rows)} claims)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
